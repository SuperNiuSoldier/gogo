"""Build the licensed, approved lettering and vector icons for the WeChat package."""
from pathlib import Path
import argparse
import base64
import io
import json
import re
import shutil
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / 'wechat/miniprogram/assets'
DEST.mkdir(parents=True, exist_ok=True)
parser = argparse.ArgumentParser()
parser.add_argument('--icons-only', action='store_true', help='Update vector assets without rebuilding the existing font subset')
args = parser.parse_args()
if not args.icons_only:
    source = ROOT / '.tools/fonts/Xiaolai-Regular.ttf'
    if not source.exists():
        raise SystemExit('Missing licensed source font; see design/assets/fonts/README.md')
    texts = []
    for folder in [ROOT / 'prd', ROOT / 'wechat/miniprogram']:
        for path in folder.rglob('*'):
            if path.suffix in {'.md', '.js', '.wxml'} and path.name != 'font.js':
                texts.append(path.read_text())
    chars = set(''.join(texts))
    chars.update(chr(i) for i in range(32, 127))
    chars.update('肉球格林又是有你的一天在草地上坐了好久风一吹毛都蓬起来了叫你回家还假装没听见吃饱睡好慢慢长大喂食喝水便便尿尿遛狗体重日记照片视频提醒记录小事生日到家')
    chars = {c for c in chars if c.isprintable()}
    font = TTFont(source)
    available = font.getBestCmap()
    missing = sorted(c for c in chars if ord(c) not in available)
    options = subset.Options()
    options.flavor = 'woff'
    options.name_IDs = ['*']
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(text=''.join(sorted(chars)))
    subsetter.subset(font)
    font.flavor = 'woff'
    out = io.BytesIO()
    font.save(out)
    source_url = 'data:font/woff;base64,' + base64.b64encode(out.getvalue()).decode()
    (DEST / 'font.js').write_text("// Generated by scripts/build_wechat_assets.py. Xiaolai, SIL OFL.\nmodule.exports = " + json.dumps({'source': source_url}, separators=(',', ':')) + ';\n')
shutil.copyfile(ROOT / 'design/assets/fonts/Xiaolai-OFL.txt', DEST / 'Xiaolai-OFL.txt')
shutil.copyfile(ROOT / 'design/assets/icons/doodle/LICENSE', DEST / 'Doodle-LICENSE.txt')

icon_js = (ROOT / 'design/prototypes/gogo-lettering/icons.js').read_text()
care_block = re.search(r'const careMarks = \{(.*?)\n\};', icon_js, re.S).group(1)
care = {name.strip("'"): paths for name, paths in re.findall(r"\s*([\w'-]+):'([^']+)'", care_block)}
mapping = {'food': 'cooking-pot', 'water': 'droplet', 'pee': 'pee', 'poop': 'poop', 'paw': 'paw-print', 'footprints': 'footprints', 'scale': 'scale', 'check': 'circle-check'}
for name in ['plus', 'moon', 'sun', 'ellipsis', 'camera', 'image', 'notebook', 'pencil', 'bell', 'circle', 'arrow-up-right', 'chevron-down', 'chevron-left', 'chevron-right', 'play', 'pause']:
    mapping[name] = name
mapping['video'] = 'camera'
for theme, color in [('light', '#272b29'), ('dark', '#f4f1e8')]:
    directory = DEST / 'icons' / theme
    directory.mkdir(parents=True, exist_ok=True)
    for name, original in mapping.items():
        if original in care:
            svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 48 48" width="48" height="48" fill="none" stroke="' + color + '" stroke-width="2.8" stroke-linecap="round" stroke-linejoin="round">' + care[original] + '</svg>'
        else:
            path = ROOT / 'design/assets/icons/doodle' / (original + '.svg')
            if not path.exists():
                raise SystemExit('Missing icon: ' + original)
            svg = path.read_text().replace('currentColor', color).replace('stroke-width="3.4"', 'stroke-width="2.8"')
        (directory / (name + '.svg')).write_text(svg)
provenance_path = DEST / 'provenance.json'
provenance = json.loads(provenance_path.read_text()) if provenance_path.exists() else {}
if not args.icons_only:
    provenance.update(font='Xiaolai Regular 3.126', license='SIL OFL 1.1', subsetCharacters=len(chars), woffBytes=len(out.getvalue()), fallbackCharacters=missing)
provenance.update(icons='Existing Doodle Icons MIT and Go狗 original care marks', source='design/prototypes/gogo-lettering', iconsPerTheme=len(mapping))
provenance_path.write_text(json.dumps(provenance, ensure_ascii=False, indent=2) + '\n')
print(json.dumps({'fontRebuilt': not args.icons_only, 'iconsPerTheme': len(mapping)}, ensure_ascii=False))
